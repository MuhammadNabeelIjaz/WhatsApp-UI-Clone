// Helper functions
export const getActiveChats = () => chats.filter(c => !c.isArchived);
export const getArchivedChats = () => chats.filter(c => c.isArchived);
export const getPinnedChats = () => chats.filter(c => c.isPinned && !c.isArchived);
export const getChatById = (id) => chats.find(c => c.id === id);
export const getGroupChats = () => chats.filter(c => c.isGroup && !c.isArchived);

// Backward-compat: old code imports { CHATS }
// Each chat gets lastMessage as string for old components
export const CHATS = chats.map(c => ({
  ...c,
  lastMessage: typeof c.lastMessage === 'object' ? c.lastMessage.text : c.lastMessage,
}));

export default chats;
